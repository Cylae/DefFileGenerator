def generate_all_classic_definitions(
    workspace_dir: Path | str,
) -> dict[str, Path]:
    """
    Compiles and writes all certified definitions for grand classic manufacturers.
    Deploys across:
    - production/
    - Definitions/Classic/
    - generated_definitions/
    - tagged_definitions/
    """
    ws = Path(workspace_dir)
    prod_dir = ws / "production"
    gen_dir = ws / "generated_definitions"
    tag_dir = ws / "tagged_definitions"
    def_classic_dir = ws / "Definitions" / "Classic"

    for d in (prod_dir, gen_dir, tag_dir, def_classic_dir):
        d.mkdir(parents=True, exist_ok=True)

    targets = get_all_classic_targets()
    generated: dict[str, Path] = {}

    for fname, cat, mfg, model, rows in targets:
        # 1. Primary write into production/
        prod_path = prod_dir / fname
        write_certified_csv(prod_path, cat, mfg, model, rows)
        generated[fname] = prod_path

        # 2. Synchronize byte-identical copies across all redundant directories
        for target_dir in (gen_dir, tag_dir, def_classic_dir):
            dest = target_dir / fname
            shutil.copy2(prod_path, dest)
            is_valid, issues = verify_file_pillars(dest)
            if not is_valid:
                raise ValueError(f"Pillar violation at {dest}:\n" + "\n".join(issues))

    return generated
